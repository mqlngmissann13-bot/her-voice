function showPromise() {

    const number = String(currentPromise + 1).padStart(3, "0");

    document.getElementById("promiseNumber").textContent =
        `Promise No. ${number}`;

    document.getElementById("promiseText").textContent =
        promises[currentPromise];

    document.getElementById("promiseCounter").textContent =
        `${currentPromise + 1} / ${promises.length}`;
}


/* =========================================
   NEXT PROMISE
========================================= */

function nextPromise() {

    currentPromise++;

    if (currentPromise >= promises.length) {
        currentPromise = 0;
    }

    showPromise();
}


/* =========================================
   PREVIOUS PROMISE
========================================= */

function previousPromise() {

    currentPromise--;

    if (currentPromise < 0) {
        currentPromise = promises.length - 1;
    }

    showPromise();
}


