function createBucketItem(text, completed = false) {

    const entry = document.createElement("div");

    entry.className = "bucket-entry";

    if (completed) {
        entry.classList.add("completed");
    }


    const textSpan = document.createElement("span");

    textSpan.textContent = text;


    const completeButton = document.createElement("button");

    completeButton.className = "complete-bucket";

    completeButton.textContent = completed ? "✓" : "☐";

    completeButton.title = "Mark as complete";


    completeButton.onclick = function() {

        toggleBucket(completeButton);

    };


    const removeButton = document.createElement("button");

    removeButton.className = "remove-bucket";

    removeButton.textContent = "×";

    removeButton.title = "Remove item";


    removeButton.onclick = function() {

        removeBucket(removeButton);

    };


    entry.appendChild(textSpan);

    entry.appendChild(completeButton);

    entry.appendChild(removeButton);

    return entry;

}


function toggleBucket(button) {

    const entry = button.parentElement;

    entry.classList.toggle("completed");

    button.textContent =
        entry.classList.contains("completed")
            ? "✓"
            : "☐";

    saveBucketList();

}


function removeBucket(button) {

    const entry = button.parentElement;

    entry.remove();

    saveBucketList();

}


function addBucketItem() {

    const input = document.getElementById("bucket-input");

    const list = document.getElementById("bucket-list");

    const text = input.value.trim();

    if (text === "") {
        return;
    }


    const entry = createBucketItem(text);

    list.appendChild(entry);

    input.value = "";

    saveBucketList();

}


