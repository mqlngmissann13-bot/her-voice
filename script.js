function createLetter(title, date, text) {

    const entry = document.createElement("div");

    entry.className = "letter-entry";


    const heading = document.createElement("div");

    heading.className = "letter-heading";

    heading.textContent = title;


    const dateElement = document.createElement("div");

    dateElement.className = "letter-date";

    dateElement.textContent = date;


    const letterText = document.createElement("p");

    letterText.textContent = text;


    const removeButton = document.createElement("button");

    removeButton.className = "remove-letter";

    removeButton.textContent = "×";

    removeButton.title = "Delete letter";


    removeButton.onclick = function() {

        entry.remove();

        saveLetters();

    };


    entry.appendChild(heading);

    entry.appendChild(dateElement);

    entry.appendChild(letterText);

    entry.appendChild(removeButton);


    return entry;

}


function addLetter() {

    const titleInput =
        document.getElementById("letter-title");

    const textInput =
        document.getElementById("letter-text");

    const list =
        document.getElementById("letter-list");


    const title = titleInput.value.trim();

    const text = textInput.value.trim();


    if (title === "" || text === "") {
        return;
    }


    const date = new Date().toLocaleDateString(
        "en-US",
        {
            month: "long",
            year: "numeric"
        }
    );


    const entry =
        createLetter(title, date, text);


    list.appendChild(entry);


    titleInput.value = "";

    textInput.value = "";


    saveLetters();

}


function removeLetter(button) {

    const entry = button.parentElement;

    entry.remove();

    saveLetters();

}


